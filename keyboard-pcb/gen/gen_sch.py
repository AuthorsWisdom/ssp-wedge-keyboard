"""Generate ssp-wedge-kb.kicad_sch from design.py (labels on every pin)."""
import uuid, math
from sexp import Sym as S, dump
from libload import get_symbol, pins
import design

PROJECT = "ssp-wedge-kb"
U = lambda: str(uuid.uuid4())
ROOT = U()
G = 1.27

def snap(v):
    return round(v / G) * G

def font(justify=None, hide=False):
    e = [S("effects"), [S("font"), [S("size"), 1.27, 1.27]]]
    if justify:
        e.append([S("justify")] + [S(j) for j in justify])
    if hide:
        e.append([S("hide"), S("yes")])
    return e

def prop(name, val, x, y, hide=False):
    return [S("property"), name, val, [S("at"), x, y, 0], font(hide=hide)]

lib_cache = {}
def sym(lib_id):
    if lib_id not in lib_cache:
        lib_cache[lib_id] = get_symbol(lib_id)
    return lib_cache[lib_id]

items = []
labels = []
ncs = []

def place(part, x, y):
    s = sym(part["lib"])
    pl = pins(s)
    ref = part["ref"]
    node = [S("symbol"), [S("lib_id"), part["lib"]], [S("at"), x, y, 0], [S("unit"), 1],
            [S("exclude_from_sim"), S("no")], [S("in_bom"), S("yes" if part.get("bom", True) else "no")],
            [S("on_board"), S("yes")], [S("dnp"), S("yes" if part.get("dnp") else "no")],
            [S("uuid"), U()]]
    ys = [p[3] for p in pl] or [0]
    top = y - max(ys) - 3.81
    node.append(prop("Reference", ref, x, top))
    node.append(prop("Value", part["value"], x, y - min(ys) + 3.81))
    node.append(prop("Footprint", part["fp"], x, y, hide=True))
    node.append(prop("Datasheet", "", x, y, hide=True))
    node.append(prop("Description", "", x, y, hide=True))
    node.append(prop("LCSC", part.get("lcsc", ""), x, y, hide=True))
    seen = set()
    for num, name, px, py, ang, ln, et in pl:
        if num in seen:
            continue
        seen.add(num)
        node.append([S("pin"), num, [S("uuid"), U()]])
    node.append([S("instances"), [S("project"), PROJECT, [S("path"), "/" + ROOT, [S("reference"), ref], [S("unit"), 1]]]])
    items.append(node)
    done = set()
    for num, name, px, py, ang, ln, et in pl:
        ex, ey = round(x + px, 4), round(y - py, 4)
        net = part["pins"].get(num, "__missing__")
        key = (ex, ey)
        if key in done:
            continue
        done.add(key)
        if net == "__missing__" or net is None:
            if et in ("power_in",) and net == "__missing__":
                raise SystemExit(f"{ref} pin {num} unassigned power pin")
            ncs.append([S("no_connect"), [S("at"), ex, ey], [S("uuid"), U()]])
            continue
        la = {0: 180, 180: 0, 90: 270, 270: 90}[int(ang) % 360]
        just = ["right", "bottom"] if la == 180 else ["left", "bottom"]
        if la in (90, 270):
            just = ["left", "bottom"] if la == 90 else ["right", "bottom"]
        labels.append([S("global_label"), net, [S("shape"), S("passive")], [S("at"), ex, ey, la],
                       [S("fields_autoplaced"), S("yes")], font(just), [S("uuid"), U()]])

def bbox(lib_id):
    pl = pins(sym(lib_id))
    if not pl:
        return (10, 10)
    xs = [p[2] for p in pl]; ys = [p[3] for p in pl]
    return (max(xs) - min(xs) + 40, max(ys) - min(ys) + 20)

parts = design.build()
core = [p for p in parts if not (p["ref"].startswith("SW") and p["value"] == "MX") and not (p["ref"].startswith("D") and p["ref"][1:].isdigit() and int(p["ref"][1:]) <= 48)]
matrix = [p for p in parts if p not in core]

# core: flow layout
x, y, rowh = 30.0, 40.0, 0.0
for p in core:
    w, h = bbox(p["lib"])
    if x + w > 800:
        x, y, rowh = 30.0, y + rowh, 0.0
    place(p, snap(x + w / 2), snap(y + h / 2))
    x += w; rowh = max(rowh, h)
y += rowh + 20

# power flags
for i, net in enumerate(["GND", "VBUS"]):
    place(dict(ref=f"#FLG0{i+1}", lib="power:PWR_FLAG", value="PWR_FLAG", fp="", pins={"1": net}, bom=False),
          snap(30 + 25 * i), snap(25))

# matrix grid
y0 = y
for p in matrix:
    if p["ref"].startswith("SW"):
        n = int(p["ref"][2:]) - 1
        r, c = divmod(n, design.COLS)
        cx, cy = 40 + c * 60, y0 + r * 30
        place(p, snap(cx), snap(cy))
        d = next(q for q in matrix if q["ref"] == f"D{n+1}")
        place(d, snap(cx + 25), snap(cy + 7.62))

title = [S("title_block"), [S("title"), "Seven Swords Wedge keyboard (RP2040, 4x12 + encoder)"],
         [S("date"), "2026-11-03"], [S("rev"), "P1"], [S("company"), "Seven Swords Productions"],
         [S("comment"), 1, "RP2040 core per Raspberry Pi Minimal RP2040 reference design (MIT)"],
         [S("comment"), 2, "Generated by gen/gen_sch.py; edit design.py, not this file"],
         [S("comment"), 3, "SPDX-License-Identifier: CERN-OHL-P-2.0  (c) 2026 Seven Swords Productions"],
         [S("comment"), 4, "J2 (SWD) is DNP: a fitted header collides with the case plate"]]

root = [S("kicad_sch"), [S("version"), 20250114], [S("generator"), "eeschema"], [S("generator_version"), "9.0"],
        [S("uuid"), ROOT], [S("paper"), "A0"], title,
        [S("lib_symbols")] + list(lib_cache.values())]
root += items + labels + ncs
root += [[S("sheet_instances"), [S("path"), "/", [S("page"), "1"]]], [S("embedded_fonts"), S("no")]]
open(f"../{PROJECT}.kicad_sch", "w").write(dump(root) + "\n")
print("symbols", len(items), "labels", len(labels), "nc", len(ncs))
